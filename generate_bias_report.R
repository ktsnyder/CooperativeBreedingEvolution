# Test 6: Geographic bias
test_geographic_bias <- function(df) {
  report <- c(
    "## Test 6: Geographic (Holarctic) Bias",
    "\n**Hypothesis:** Holarctic species are overrepresented in the dataset.\n"
  )
  
  if ("GeographicRegion_Jetz" %in% colnames(df)) {
    # Test for FS data
    cont_table_fs <- table(
      Region = df$GeographicRegion_Jetz,
      FS_Data = ifelse(df$HaveFSData, "Has FS Data", "No FS Data")
    )
    
    chi_test_fs <- chisq.test(cont_table_fs)
    props_fs <- prop.table(cont_table_fs, margin = 1)
    
    report <- c(report,
      "### Female Song Data by Geographic Region",
      "```",
      capture.output(print(cont_table_fs)),
      "```",
      "\n### Proportions",
      "```",
      capture.output(print(round(props_fs, 3))),
      "```",
      paste("\n- Chi-squared test: χ² =", round(chi_test_fs$statistic, 3),
            ", df =", chi_test_fs$parameter,
            ", p =", format.pval(chi_test_fs$p.value, digits = 3)),
      "\n### Result",
      ifelse(chi_test_fs$p.value < 0.05,
             paste("**Significant geographic bias detected:** Holarctic species have",
                   ifelse(props_fs["Holarctic", "Has FS Data"] > props_fs["Tropical", "Has FS Data"],
                          "MORE", "LESS"),
                   "female song data than Tropical species."),
             "No significant geographic bias for female song data.")
    )
    
    # Test for CB data
    cont_table_cb <- table(
      Region = df$GeographicRegion_Jetz,
      CB_Data = ifelse(df$HaveCBData, "Has CB Data", "No CB Data")
    )
    
    chi_test_cb <- chisq.test(cont_table_cb)
    props_cb <- prop.table(cont_table_cb, margin = 1)
    
    report <- c(report,
      "\n\n### Cooperative Breeding Data by Geographic Region",
      "```",
      capture.output(print(cont_table_cb)),
      "```",
      paste("\n- Chi-squared test: χ² =", round(chi_test_cb$statistic, 3),
            ", df =", chi_test_cb$parameter,
            ", p =", format.pval(chi_test_cb$p.value, digits = 3)),
      paste("- Proportion with CB data: Holarctic =", 
            round(props_cb["Holarctic", "Has CB Data"], 3),
            ", Tropical =", round(props_cb["Tropical", "Has CB Data"], 3))
    )
    
    # Test for both
    cont_table_both <- table(
      Region = df$GeographicRegion_Jetz,
      Both_Data = ifelse(df$HaveBothData, "Has Both", "Missing Data")
    )
    
    chi_test_both <- chisq.test(cont_table_both)
    props_both <- prop.table(cont_table_both, margin = 1)
    
    report <- c(report,
      "\n\n### Both FS and CB Data by Geographic Region",
      "```",
      capture.output(print(cont_table_both)),
      "```",
      paste("\n- Chi-squared test: χ² =", round(chi_test_both$statistic, 3),
            ", df =", chi_test_both$parameter,
            ", p =", format.pval(chi_test_both$p.value, digits = 3)),
      paste("- Proportion with both datasets: Holarctic =", 
            round(props_both["Holarctic", "Has Both"], 3),
            ", Tropical =", round(props_both["Tropical", "Has Both"], 3)),
      "\n### Overall Geographic Bias Result",
      ifelse(chi_test_fs$p.value < 0.05 | chi_test_cb$p.value < 0.05 | chi_test_both$p.value < 0.05,
             "**Significant geographic bias detected in data availability.**",
             "No significant geographic bias detected.")
    )
  }
  
  report <- c(report, "\n---\n")
  return(report)
}

