#' Generate comprehensive bias testing report
#'
#' @param df Data frame with species data
#' @param tree Phylogenetic tree
#' @param output_file Path to output markdown file
#' @param output_dir Directory for saving plots and intermediate files
#' @return Invisibly returns the full report text
generate_bias_report <- function(df,
                               tree,
                               output_file = "Bias_Test_Results.md",
                               output_dir = "Outputs/BiasTestReport") {
  
  # Create output directory
  if (!dir.exists(output_dir)) {
    dir.create(output_dir, recursive = TRUE)
  }
  
  # Initialize report
  report <- c(
    "# Bias Testing Results",
    paste("\n**Date:**", Sys.Date()),
    paste("**Generated by:** generate_bias_report.R"),
    paste("**Data file:** Data_R_2025-06-07.csv"),
    paste("**Tree file:** 2022-03-16ConsensusPasserineTreeHackett4_1000_OscineSubset.nex"),
    "\n## Overview",
    "\nThis report presents results from comprehensive bias testing to identify potential sampling biases in the dataset. We tested six specific hypotheses about data availability biases that could affect evolutionary analyses of cooperative breeding and female song in passerine birds.\n"
  )
  
  # Prepare data
  df_work <- df[df$species %in% tree$tip.label, ]
  
  # Add geographic regions if needed
  if (!"GeographicRegion_Jetz" %in% colnames(df_work)) {
    df_work$GeographicRegion_Jetz <- NA
    df_work$GeographicRegion_Jetz[which(df_work$Realm_Jetz2011 %in% c("PA", "NeA"))] <- "Holarctic"
    df_work$GeographicRegion_Jetz[which(df_work$Realm_Jetz2011 %in% c("AT", "NT", "IM", "AA", "OC"))] <- "Tropical"
  }
  
  # Add data availability indicators
  df_work$HaveFSData <- !is.na(df_work$FemaleSong_Agg01)
  df_work$HaveCBData <- !is.na(df_work$HighConfidence_Coop)
  df_work$HaveBothData <- df_work$HaveFSData & df_work$HaveCBData
  
  # Dataset summary
  report <- c(report,
    "## Dataset Summary",
    paste("\n- Total species in tree:", length(tree$tip.label)),
    paste("- Species with data:", nrow(df_work)),
    paste("- Species with Female Song data:", sum(df_work$HaveFSData)),
    paste("- Species with Cooperative Breeding data:", sum(df_work$HaveCBData)),
    paste("- Species with both FS and CB data:", sum(df_work$HaveBothData)),
    "\n---\n"
  )
  
  # Test 1: Cooperative breeding bias
  report <- c(report, test_cooperative_breeding_bias(df_work))
  
  # Test 2: Social system biases
  report <- c(report, test_social_system_biases(df_work))
  
  # Test 3: Territoriality bias for complex breeding systems
  report <- c(report, test_territoriality_breeding_bias(df_work))
  
  # Test 4: Sexual dichromatism bias
  report <- c(report, test_dichromatism_bias(df_work))
  
  # Test 5: Sexual size dimorphism bias
  report <- c(report, test_size_dimorphism_bias(df_work))
  
  # Test 6: Geographic (Holarctic) bias
  report <- c(report, test_geographic_bias(df_work))
  
  # Summary and recommendations
  report <- c(report, generate_summary_recommendations(df_work))
  
  # Write report
  writeLines(report, output_file)
  cat("Report saved to:", output_file, "\n")
  
  invisible(report)
}

# Test 1: Cooperative breeding bias
test_cooperative_breeding_bias <- function(df) {
  report <- c(
    "## Test 1: Cooperative Breeding Bias",
    "\n**Hypothesis:** Cooperative breeding species have a greater likelihood of being studied to a degree where female song presence or absence can be determined.\n"
  )
  
  # Create contingency table
  cont_table <- table(
    CB = ifelse(df$HighConfidence_Coop == 1, "Cooperative", "Non-cooperative"),
    FS_Data = ifelse(df$HaveFSData, "Has FS Data", "No FS Data")
  )
  
  # Chi-square test
  chi_test <- chisq.test(cont_table)
  
  # Calculate proportions
  props <- prop.table(cont_table, margin = 1)
  
  report <- c(report,
    "### Contingency Table",
    "```",
    capture.output(print(cont_table)),
    "```",
    "\n### Proportions (by row)",
    "```",
    capture.output(print(round(props, 3))),
    "```",
    "\n### Statistical Test",
    paste("- Chi-squared test: χ² =", round(chi_test$statistic, 3), 
          ", df =", chi_test$parameter, 
          ", p =", format.pval(chi_test$p.value, digits = 3)),
    "\n### Result",
    ifelse(chi_test$p.value < 0.05,
           paste("**Significant bias detected (p < 0.05):** Cooperative breeders have",
                 ifelse(props["Cooperative", "Has FS Data"] > props["Non-cooperative", "Has FS Data"],
                        "MORE", "LESS"),
                 "female song data than non-cooperative species."),
           "No significant bias detected (p ≥ 0.05)."),
    "\n---\n"
  )
  
  return(report)
}

# Test 2: Social system biases
test_social_system_biases <- function(df) {
  report <- c(
    "## Test 2: Social System Biases",
    "\n**Hypothesis:** Birds that group together (colonial species, familial-living species, and polygynous species) are more likely to be studied.\n"
  )
  
  social_cols <- c("Griesser2023.Colonial01", "Griesser2017FamilialLiving", "Final.polygyny")
  social_labels <- c("Colonial", "Familial Living", "Polygynous")
  
  for (i in seq_along(social_cols)) {
    col <- social_cols[i]
    label <- social_labels[i]
    
    if (col %in% colnames(df) && sum(!is.na(df[[col]])) > 10) {
      report <- c(report, paste("\n### ", label))
      
      # Create contingency table
      cont_table <- table(
        Social = ifelse(df[[col]] == 1, paste(label, "Yes"), paste(label, "No")),
        FS_Data = ifelse(df$HaveFSData, "Has FS Data", "No FS Data")
      )
      
      # Skip if one category is too small
      if (min(table(df[[col]])) < 5) {
        report <- c(report, "\nInsufficient data for statistical test.\n")
        next
      }
      
      # Chi-square test
      chi_test <- chisq.test(cont_table)
      props <- prop.table(cont_table, margin = 1)
      
      report <- c(report,
        "```",
        capture.output(print(cont_table)),
        "```",
        paste("\n- Chi-squared test: χ² =", round(chi_test$statistic, 3), 
              ", df =", chi_test$parameter, 
              ", p =", format.pval(chi_test$p.value, digits = 3)),
        paste("- Proportion with FS data:", label, "Yes =", 
              round(props[paste(label, "Yes"), "Has FS Data"], 3),
              ", No =", round(props[paste(label, "No"), "Has FS Data"], 3))
      )
    }
  }
  
  report <- c(report, "\n---\n")
  return(report)
}

# Test 3: Territoriality bias for complex breeding systems
test_territoriality_breeding_bias <- function(df) {
  report <- c(
    "## Test 3: Territoriality and Complex Breeding Systems",
    "\n**Hypothesis:** It is more likely for complex breeding systems to be detected in year-round territorial birds.\n"
  )
  
  # Test if year-round territorial birds are more likely to have CB data
  if ("Territory_12vs3" %in% colnames(df)) {
    df$YearRoundTerritorial <- ifelse(df$Territory_12vs3 == 1, "Year-round", "Seasonal")
    
    cont_table <- table(
      Territory = df$YearRoundTerritorial,
      CB_Data = ifelse(df$HaveCBData, "Has CB Data", "No CB Data")
    )
    
    chi_test <- chisq.test(cont_table)
    props <- prop.table(cont_table, margin = 1)
    
    report <- c(report,
      "\n### Cooperative Breeding Data by Territoriality",
      "```",
      capture.output(print(cont_table)),
      "```",
      "\n### Proportions",
      "```",
      capture.output(print(round(props, 3))),
      "```",
      paste("\n- Chi-squared test: χ² =", round(chi_test$statistic, 3), 
            ", df =", chi_test$parameter, 
            ", p =", format.pval(chi_test$p.value, digits = 3)),
      "\n### Result",
      ifelse(chi_test$p.value < 0.05,
             paste("**Significant bias detected:** Year-round territorial species have",
                   ifelse(props["Year-round", "Has CB Data"] > props["Seasonal", "Has CB Data"],
                          "MORE", "LESS"),
                   "cooperative breeding data."),
             "No significant bias detected.")
    )
    
    # Also test for both FS and CB data
    cont_table2 <- table(
      Territory = df$YearRoundTerritorial,
      Both_Data = ifelse(df$HaveBothData, "Has Both", "Missing Data")
    )
    
    chi_test2 <- chisq.test(cont_table2)
    props2 <- prop.table(cont_table2, margin = 1)
    
    report <- c(report,
      "\n\n### Both FS and CB Data by Territoriality",
      "```",
      capture.output(print(cont_table2)),
      "```",
      paste("\n- Chi-squared test: χ² =", round(chi_test2$statistic, 3), 
            ", df =", chi_test2$parameter, 
            ", p =", format.pval(chi_test2$p.value, digits = 3)),
      paste("- Proportion with both datasets: Year-round =", 
            round(props2["Year-round", "Has Both"], 3),
            ", Seasonal =", round(props2["Seasonal", "Has Both"], 3))
    )
  }
  
  report <- c(report, "\n---\n")
  return(report)
}

# Test 4: Sexual dichromatism bias
test_dichromatism_bias <- function(df) {
  report <- c(
    "## Test 4: Sexual Dichromatism Bias",
    "\n**Hypothesis:** Greater sexual dichromatism leads to a higher rate of identification of female song, so species with lower sexual dichromatism would either be underrepresented in the dataset overall or would be more likely to be miscategorized as female song absent.\n"
  )
  
  if ("logMaleFemalePlumageDiffAbs" %in% colnames(df)) {
    # Remove infinite values
    df_plumage <- df[is.finite(df$logMaleFemalePlumageDiffAbs), ]
    
    # Test 1: Do dichromatic species have more FS data?
    t_test1 <- t.test(logMaleFemalePlumageDiffAbs ~ HaveFSData, data = df_plumage)
    
    # Summary stats
    summary_stats <- df_plumage %>%
      group_by(HaveFSData) %>%
      summarise(
        n = n(),
        mean = round(mean(logMaleFemalePlumageDiffAbs, na.rm = TRUE), 3),
        sd = round(sd(logMaleFemalePlumageDiffAbs, na.rm = TRUE), 3),
        .groups = "drop"
      )
    
    report <- c(report,
      "### Test 4a: Dichromatism by Data Availability",
      "\n**Question:** Are dichromatic species more likely to have female song data?\n",
      "\n#### Summary Statistics",
      "```",
      capture.output(print(summary_stats)),
      "```",
      "\n#### Statistical Test",
      paste("- Welch Two Sample t-test: t =", round(t_test1$statistic, 3),
            ", df =", round(t_test1$parameter, 1),
            ", p =", format.pval(t_test1$p.value, digits = 3)),
      paste("- Mean difference:", round(diff(t_test1$estimate), 3)),
      "\n#### Result",
      ifelse(t_test1$p.value < 0.05,
             paste("**Significant difference:** Species",
                   ifelse(t_test1$estimate[2] > t_test1$estimate[1], "WITH", "WITHOUT"),
                   "female song data are more dichromatic."),
             "No significant difference in dichromatism by data availability.")
    )
    
    # Test 2: Among species with data, do dichromatic species differ in FS presence?
    df_with_fs <- df_plumage[!is.na(df_plumage$FemaleSong_Agg01), ]
    if (nrow(df_with_fs) > 10) {
      t_test2 <- t.test(logMaleFemalePlumageDiffAbs ~ FemaleSong_Agg01, data = df_with_fs)
      
      summary_stats2 <- df_with_fs %>%
        group_by(FemaleSong_Agg01) %>%
        summarise(
          n = n(),
          mean = round(mean(logMaleFemalePlumageDiffAbs, na.rm = TRUE), 3),
          sd = round(sd(logMaleFemalePlumageDiffAbs, na.rm = TRUE), 3),
          .groups = "drop"
        )
      
      report <- c(report,
        "\n### Test 4b: Dichromatism by Female Song Presence",
        "\n**Question:** Among species with data, are dichromatic species more likely to have female song?\n",
        "\n#### Summary Statistics",
        "```",
        capture.output(print(summary_stats2)),
        "```",
        "\n#### Statistical Test",
        paste("- Welch Two Sample t-test: t =", round(t_test2$statistic, 3),
              ", df =", round(t_test2$parameter, 1),
              ", p =", format.pval(t_test2$p.value, digits = 3)),
        paste("- Mean difference:", round(diff(t_test2$estimate), 3)),
        "\n#### Result",
        ifelse(t_test2$p.value < 0.05,
               paste("**Significant difference:** Species with female song",
                     ifelse(t_test2$estimate[2] < t_test2$estimate[1], "ABSENT", "PRESENT"),
                     "are more dichromatic."),
               "No significant difference in dichromatism by female song presence.")
      )
    }
  }
  
  report <- c(report, "\n---\n")
  return(report)
}

